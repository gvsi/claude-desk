export interface IconProps {
  name: IconName;
  /** Drawn size in px; 20 unless the component needs it smaller. */
  size?: IconSize;
  className?: string;
}

/** The 24-unit grid's stroke that draws 1.5 px at `size`: 1.8 units at 20 px. */
function strokeFor(size: IconSize): number {
  return (1.5 * 24) / size;
}

export function Icon({ name, size = 20, className }: IconProps) {
  return (
    <svg
      className={className}
      aria-hidden="true"
      focusable="false"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeFor(size)}
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {SHAPES[name]}
    </svg>
  );
}
