"""DeskData: what the app stands on and what outlives a deploy.

A VPC with public and isolated subnets and no NAT gateway (tasks reach images, Secrets Manager
and the Anthropic API through public IPs); private, encrypted Postgres; secrets managed
by Secrets Manager; the security groups, database rules included, so no rule waits on the
service; the CloudFront origin-facing prefix list, looked up at deploy; the ECS cluster; and the
one-off admin task that migrates and sets role passwords.
"""

import json
from dataclasses import dataclass

from aws_cdk import CfnOutput, Duration, Fn, RemovalPolicy, SecretValue, Stack
from aws_cdk import aws_ec2 as ec2
from aws_cdk import aws_ecs as ecs
from aws_cdk import aws_iam as iam
from aws_cdk import aws_logs as logs
from aws_cdk import aws_rds as rds
from aws_cdk import aws_secretsmanager as secretsmanager
from aws_cdk import custom_resources as cr
from constructs import Construct

from stacks.config import DeskConfig
from stacks.image import desk_image

DATABASE_NAME = "desk"
# The ECS cluster, by name: the Express service names it, and the scripts run the admin task in it.
CLUSTER_NAME = "desk"
ADMIN_ROLE = "desk_admin"
# The process roles migration 0001_core creates NOLOGIN; the admin task gives them these passwords.
KERNEL_ROLE, API_ROLE, MOCKPAY_ROLE = "desk_kernel", "desk_api", "desk_mockpay"
# Secrets Manager draws from letters, digits and punctuation; what is left once these are
# excluded is 0-9 and a-f, so a 64-character value is 32 random bytes in hex.
_NOT_HEX = "ghijklmnopqrstuvwxyz"
# AWS's managed list of the addresses CloudFront uses to reach origins, in every region.
CLOUDFRONT_ORIGIN_FACING = "com.amazonaws.global.cloudfront.origin-facing"


@dataclass(frozen=True)
class DeskSecrets:
    """Every secret the Desk runs on, generated by Secrets Manager except `typesafe`, which starts
    as the fixed value `unset` (Jev off); no value is ever in a template. `anthropic`, `typesafe` and
    `passcode_hash` start as placeholders the owner overwrites with
    infra/scripts/set_secret.py, which tags each with the version it wrote for the deploy
    preflight. Never change a generator after the first deploy: CloudFormation would generate a new
    value (test_data_stack.py freezes each one)."""

    admin: secretsmanager.ISecret          # desk/db/admin: the master user, desk_admin
    kernel_db: secretsmanager.ISecret      # desk/db/kernel: desk_kernel's login
    api_db: secretsmanager.ISecret         # desk/db/api: desk_api's login
    mockpay_db: secretsmanager.ISecret     # desk/db/mockpay: desk_mockpay's login
    signing_seed: secretsmanager.ISecret   # desk/signing-seed: the ledger's Ed25519 seed, 64 hex
    mockpay_key: secretsmanager.ISecret    # desk/mockpay-key: the kernel's key to mock payments, 64 hex
    anthropic: secretsmanager.ISecret      # desk/anthropic-api-key: owner-set
    typesafe: secretsmanager.ISecret       # desk/typesafe-api-key: owner-set, kernel only
    passcode_hash: secretsmanager.ISecret  # desk/passcode-hash: owner-set


class DeskData(Stack):
    def __init__(self, scope: Construct, construct_id: str, *, config: DeskConfig, **kwargs) -> None:
        super().__init__(
            scope, construct_id, description="Claude Desk data: network, database, secrets, admin task", **kwargs
        )

        self.vpc = ec2.Vpc(
            self,
            "Vpc",
            max_azs=2,
            nat_gateways=0,
            subnet_configuration=[
                ec2.SubnetConfiguration(name="public", subnet_type=ec2.SubnetType.PUBLIC, cidr_mask=24),
                ec2.SubnetConfiguration(name="isolated", subnet_type=ec2.SubnetType.PRIVATE_ISOLATED, cidr_mask=24),
            ],
        )
        # The function CDK adds to strip the VPC's default security group is plain Node.js; run it on
        # arm64 like all of the Desk's compute.
        restrict_default = self.node.find_child("Custom::VpcRestrictDefaultSGCustomResourceProvider")
        restrict_default.node.find_child("Handler").add_property_override("Architectures", ["arm64"])

        # The app task: the API on 8700 for the load balancer, which lives in this VPC.
        self.app_security_group = ec2.SecurityGroup(
            self, "AppSecurityGroup", vpc=self.vpc, description="Claude Desk app task", allow_all_outbound=True
        )
        self.app_security_group.add_ingress_rule(
            ec2.Peer.ipv4(self.vpc.vpc_cidr_block), ec2.Port.tcp(8700), "The API, from the load balancer in this VPC"
        )
        # The admin task takes no connections.
        self.admin_security_group = ec2.SecurityGroup(
            self, "AdminSecurityGroup", vpc=self.vpc, description="Claude Desk admin task", allow_all_outbound=True
        )
        # Postgres, from the app and admin tasks only; both rules live here, never on the service.
        self.db_security_group = ec2.SecurityGroup(
            self, "DbSecurityGroup", vpc=self.vpc, description="Claude Desk database", allow_all_outbound=False
        )
        for name, peer in (("app", self.app_security_group), ("admin", self.admin_security_group)):
            self.db_security_group.add_ingress_rule(peer, ec2.Port.tcp(5432), f"Postgres from the {name} task")

        self.secrets = DeskSecrets(
            admin=self._login_secret("AdminDbSecret", "desk/db/admin", ADMIN_ROLE),
            kernel_db=self._login_secret("KernelDbSecret", "desk/db/kernel", KERNEL_ROLE),
            api_db=self._login_secret("ApiDbSecret", "desk/db/api", API_ROLE),
            mockpay_db=self._login_secret("MockpayDbSecret", "desk/db/mockpay", MOCKPAY_ROLE),
            signing_seed=self._hex_secret("SigningSeed", "desk/signing-seed", "The ledger's Ed25519 signing seed"),
            mockpay_key=self._hex_secret("MockpayKey", "desk/mockpay-key", "The kernel's mock payments key"),
            anthropic=self._owner_secret("AnthropicApiKey", "desk/anthropic-api-key", "The Anthropic API key"),
            typesafe=secretsmanager.Secret(
                self, "TypesafeApiKey", secret_name="desk/typesafe-api-key",
                description="The TypeSafe Jev API key; set by the owner with infra/scripts/set_secret.py",
                secret_string_value=SecretValue.unsafe_plain_text("unset"),
                removal_policy=RemovalPolicy.DESTROY,
            ),
            passcode_hash=self._owner_secret("PasscodeHash", "desk/passcode-hash", "The demo passcode's hash"),
        )

        engine = rds.DatabaseInstanceEngine.postgres(version=rds.PostgresEngineVersion.VER_16_13)
        parameters = rds.ParameterGroup(
            self,
            "DbParameters",
            engine=engine,
            description="Claude Desk Postgres: TLS only, statements never logged",
            parameters={
                "rds.force_ssl": "1",
                "log_statement": "none",
                # A failing statement's text is logged at the default `error`; the admin task's
                # ALTER ROLE carries a password verifier, so failed statements stay out too.
                "log_min_error_statement": "panic",
            },
        )
        self.db = rds.DatabaseInstance(
            self,
            "Db",
            engine=engine,
            instance_type=ec2.InstanceType.of(ec2.InstanceClass.BURSTABLE4_GRAVITON, ec2.InstanceSize.SMALL),
            vpc=self.vpc,
            vpc_subnets=ec2.SubnetSelection(subnet_type=ec2.SubnetType.PRIVATE_ISOLATED),
            security_groups=[self.db_security_group],
            credentials=rds.Credentials.from_secret(self.secrets.admin),
            parameter_group=parameters,
            database_name=DATABASE_NAME,
            allocated_storage=20,
            storage_type=rds.StorageType.GP3,
            storage_encrypted=True,
            publicly_accessible=False,
            multi_az=False,
            backup_retention=Duration.days(7),
            deletion_protection=True,
            removal_policy=RemovalPolicy.SNAPSHOT,
        )

        self.cloudfront_prefix_list_id = self._cloudfront_prefix_list_id()
        self.cluster = ecs.Cluster(
            self, "Cluster", cluster_name=CLUSTER_NAME, vpc=self.vpc, enable_fargate_capacity_providers=True
        )
        self.admin_task_definition = self._admin_task(config)

        # Read by deploy.sh and run_admin_task.py (the admin task runs in the public subnets with
        # a public IP, the only way out without NAT) and by the smoke checks.
        outputs = {
            "ClusterName": self.cluster.cluster_name,
            "AdminTaskDefinitionArn": self.admin_task_definition.task_definition_arn,
            "PublicSubnetIds": Fn.join(",", [subnet.subnet_id for subnet in self.vpc.public_subnets]),
            "AdminSecurityGroupId": self.admin_security_group.security_group_id,
            "AppSecurityGroupId": self.app_security_group.security_group_id,
            "CloudFrontPrefixListId": self.cloudfront_prefix_list_id,
        }
        for name, value in outputs.items():
            CfnOutput(self, name, value=value)

    def _cloudfront_prefix_list_id(self) -> str:
        """The origin-facing prefix list's ID, looked up when the stack deploys, so synth needs no
        credentials. The origin's security group admits CloudFront through it (DeskApp)."""
        call = cr.AwsSdkCall(
            service="EC2",
            action="describeManagedPrefixLists",
            parameters={"Filters": [{"Name": "prefix-list-name", "Values": [CLOUDFRONT_ORIGIN_FACING]}]},
            physical_resource_id=cr.PhysicalResourceId.of(CLOUDFRONT_ORIGIN_FACING),
            output_paths=["PrefixLists.0.PrefixListId"],
        )
        lookup = cr.AwsCustomResource(
            self,
            "CloudFrontPrefixList",
            on_create=call,
            on_update=call,
            policy=cr.AwsCustomResourcePolicy.from_statements(
                [iam.PolicyStatement(actions=["ec2:DescribeManagedPrefixLists"], resources=["*"])]
            ),
            install_latest_aws_sdk=False,
        )
        # The lookup runs in the one function CDK shares among a stack's AwsCustomResources, plain
        # Node.js; run it on arm64 like all of the Desk's compute.
        function = self.node.find_child(f"AWS{cr.AwsCustomResource.PROVIDER_FUNCTION_UUID.replace('-', '')}")
        function.node.default_child.add_property_override("Architectures", ["arm64"])
        return lookup.get_response_field("PrefixLists.0.PrefixListId")

    def _admin_task(self, config: DeskConfig) -> ecs.FargateTaskDefinition:
        """`python -m desk.ops.admin migrate-and-roles` through the image's entrypoint, which composes
        ADMIN_DATABASE_URL from the parts below: the seam's admin column. deploy.sh runs it in the
        public subnets with a public IP and the admin group before each DeskApp deploy."""
        task = ecs.FargateTaskDefinition(
            self,
            "AdminTask",
            family="desk-admin",
            cpu=512,
            memory_limit_mib=1024,
            runtime_platform=ecs.RuntimePlatform(
                cpu_architecture=ecs.CpuArchitecture.ARM64,
                operating_system_family=ecs.OperatingSystemFamily.LINUX,
            ),
        )
        log_group = logs.LogGroup(
            self, "AdminLogs", retention=logs.RetentionDays.TWO_WEEKS, removal_policy=RemovalPolicy.DESTROY
        )
        task.add_container(
            "admin",
            container_name="admin",
            image=desk_image(self, config),
            essential=True,
            command=["python", "-m", "desk.ops.admin", "migrate-and-roles"],
            environment={
                "DESK_DB_URLS": "ADMIN",
                "ADMIN_DB_USER": ADMIN_ROLE,
                "DB_HOST": self.db.db_instance_endpoint_address,
                "DB_PORT": self.db.db_instance_endpoint_port,
                "DB_NAME": DATABASE_NAME,
            },
            # Only the master login and the three role passwords it sets; the execution role
            # fetches them for the container, and the task role holds nothing.
            secrets={
                "ADMIN_DB_PASSWORD": ecs.Secret.from_secrets_manager(self.secrets.admin, "password"),
                "KERNEL_ROLE_PASSWORD": ecs.Secret.from_secrets_manager(self.secrets.kernel_db, "password"),
                "API_ROLE_PASSWORD": ecs.Secret.from_secrets_manager(self.secrets.api_db, "password"),
                "MOCKPAY_ROLE_PASSWORD": ecs.Secret.from_secrets_manager(self.secrets.mockpay_db, "password"),
            },
            # Blocking, so the last lines, which deploy.sh prints, are never dropped.
            logging=ecs.LogDrivers.aws_logs(
                stream_prefix="admin", log_group=log_group, mode=ecs.AwsLogDriverMode.BLOCKING
            ),
        )
        return task

    def _login_secret(self, construct_id: str, name: str, role: str) -> secretsmanager.Secret:
        """`{"username": <role>, "password": <32 letters and digits>}`, generated by Secrets Manager."""
        return secretsmanager.Secret(
            self,
            construct_id,
            secret_name=name,
            description=f"Postgres login for {role}",
            generate_secret_string=secretsmanager.SecretStringGenerator(
                secret_string_template=json.dumps({"username": role}, separators=(",", ":")),
                generate_string_key="password",
                password_length=32,
                exclude_punctuation=True,
                include_space=False,
            ),
            removal_policy=RemovalPolicy.DESTROY,
        )

    def _hex_secret(self, construct_id: str, name: str, purpose: str) -> secretsmanager.Secret:
        """64 characters of 0-9a-f, retained when the stack is deleted (the seed keeps the ledger's
        signatures verifiable). A stack created again needs them deleted or imported first."""
        return secretsmanager.Secret(
            self,
            construct_id,
            secret_name=name,
            description=f"{purpose}, 64 hex characters",
            generate_secret_string=secretsmanager.SecretStringGenerator(
                password_length=64,
                exclude_characters=_NOT_HEX,
                exclude_uppercase=True,
                exclude_punctuation=True,
                include_space=False,
            ),
            removal_policy=RemovalPolicy.RETAIN,
        )

    def _owner_secret(self, construct_id: str, name: str, purpose: str) -> secretsmanager.Secret:
        """A generated placeholder until the owner sets the value with set_secret.py."""
        return secretsmanager.Secret(
            self,
            construct_id,
            secret_name=name,
            description=f"{purpose}; set by the owner with infra/scripts/set_secret.py",
            generate_secret_string=secretsmanager.SecretStringGenerator(
                password_length=32, exclude_punctuation=True, include_space=False
            ),
            removal_policy=RemovalPolicy.DESTROY,
        )
