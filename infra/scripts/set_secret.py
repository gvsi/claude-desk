"""Set an owner-held model key or the passcode hash.

    uv run --project infra python infra/scripts/set_secret.py desk/anthropic-api-key
    uv run --project infra python infra/scripts/set_secret.py desk/typesafe-api-key
    uv run --project backend python backend/scripts/hash_passcode.py \\
      | uv run --project infra python infra/scripts/set_secret.py desk/passcode-hash --stdin

DeskData creates these secrets as placeholders: generated ones, and `unset` for the TypeSafe key. This writes the owner's value (typed
without echo, or piped in with --stdin), then tags the secret `owner-set=<the version it wrote>`.
For the required Anthropic key and passcode hash, deploy preflight requires that version to be
current, so a value written since by anything else (CloudFormation generating the placeholder
again, say) stops the deploy. The TypeSafe key is optional. It prints the secret's ID and new version, never the value. Any other secret ID is refused before any
AWS call; every other secret is generated by Secrets Manager.

Exit status: 0 set, 1 an empty value or an AWS error, 2 a usage error.
"""

import argparse
import getpass
import sys
from typing import TextIO

import boto3
from botocore.exceptions import BotoCoreError, ClientError

REGION = "us-west-2"
OWNER_SECRETS = ("desk/anthropic-api-key", "desk/typesafe-api-key", "desk/passcode-hash")
OWNER_SET_TAG = "owner-set"      # its value: the version this script wrote


def _fail(message: str, status: int) -> int:
    print(f"set_secret: {message}", file=sys.stderr)
    return status


def main(argv: list[str] | None = None, *, client=None, stdin: TextIO | None = None) -> int:
    parser = argparse.ArgumentParser(description="Set an owner-held model key or the passcode hash, without echo.")
    parser.add_argument("secret_id", help=" or ".join(OWNER_SECRETS))
    parser.add_argument("--stdin", action="store_true", help="read the value from a pipe (the passcode hash)")
    args = parser.parse_args(argv)
    stdin = sys.stdin if stdin is None else stdin

    if args.secret_id not in OWNER_SECRETS:
        return _fail(f"only {' and '.join(OWNER_SECRETS)} are set by hand; Secrets Manager generates the rest", 2)
    if args.stdin and stdin.isatty():
        return _fail("--stdin reads a piped value; to type the value hidden, leave out --stdin", 2)

    value = (stdin.read() if args.stdin else getpass.getpass(f"{args.secret_id} (hidden): ")).strip()
    if not value:
        return _fail("the value is empty; nothing was written", 1)

    client = boto3.client("secretsmanager", region_name=REGION) if client is None else client
    try:
        version = client.put_secret_value(SecretId=args.secret_id, SecretString=value)["VersionId"]
        client.tag_resource(SecretId=args.secret_id, Tags=[{"Key": OWNER_SET_TAG, "Value": version}])
    except ClientError as error:
        code = error.response.get("Error", {}).get("Code", "error")
        return _fail(f"{args.secret_id}: {code} (deploy DeskData first, with your AWS profile)", 1)
    except BotoCoreError as error:
        return _fail(f"{args.secret_id}: {type(error).__name__}", 1)
    print(f"set {args.secret_id}, version {version}, tagged {OWNER_SET_TAG}={version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
